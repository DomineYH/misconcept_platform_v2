import assert from 'node:assert/strict';
import {chromium} from 'playwright';

const base = `http://127.0.0.1:${process.argv[2]}`;
const browser = await chromium.launch({headless:true});
const page = await browser.newPage();
const errors = [], requests = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => {
  if (request.method() === 'POST' && request.url() === `${base}/admin/comparisons`) requests.push(request.postDataJSON());
});
await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
try {
  await page.goto(`${base}/login`);
  await page.locator('[name=username]').fill('comparison_admin');
  await page.locator('[name=password]').fill('comparison-password');
  await Promise.all([page.waitForURL(url => url.pathname !== '/login'),page.locator('button[type=submit]').click()]);
  await page.goto(`${base}/admin/scenarios/new`);
  await page.locator('[data-step="1"]').click();
  await page.getByLabel('공개 문제 상황',{exact:true}).fill('Public mentor comparison');
  await page.getByLabel('학습목표',{exact:true}).fill('Compare fractions');
  await page.locator('[data-step="2"]').click();
  await page.getByLabel('학생봇 이름',{exact:true}).fill('Student');
  await page.getByLabel('목표 오개념',{exact:true}).fill('Larger denominator');
  await page.getByLabel('학생봇 행동 지시',{exact:true}).fill('Explain');
  await page.locator('[data-step="3"]').click();
  await page.getByLabel('멘토 사용 모드').selectOption('manual');
  await page.getByLabel('멘토 이름',{exact:true}).fill('Mentor');
  await page.getByLabel('멘토 행동 지시',{exact:true}).fill('Coach the target pair');
  await page.getByLabel('멘토 사용 모드').selectOption('off');
  await page.getByRole('button',{name:'모델 비교 열기',exact:true}).click();
  await page.getByLabel('비교 대상').selectOption('mentor');
  async function addPair() {
    await page.getByRole('button',{name:'완료 쌍 추가',exact:true}).click();
    await page.getByLabel('이력 1 교사',{exact:true}).fill('Target question');
    await page.getByLabel('이력 1 학생',{exact:true}).fill('Target answer');
  }
  await addPair();
  const start = page.getByRole('button',{name:'비교 실행',exact:true});
  await start.click();
  assert.equal(requests.length,0,'off blocks before provider admission');
  await page.getByLabel('멘토 사용 모드').selectOption('manual');
  await page.getByRole('button',{name:'비교 닫기',exact:true}).click();
  await page.getByRole('button',{name:'모델 비교 열기',exact:true}).click();
  const p1 = page.getByRole('article',{name:'패널 1',exact:true});
  assert.match(await p1.innerText(),/성공/,'current mentor role verification is visible');
  const coaching = 'Live coaching <img src=x onerror="window.s5xss=1">';
  await page.getByLabel('패널 1 최대 출력 토큰',{exact:true}).fill('1500');
  await start.click();
  await p1.getByText(coaching,{exact:true}).waitFor();
  assert.match(await p1.innerText(),/첫 본문 N\/A/);
  assert.equal(requests[0].current_message,null);
  assert.equal(requests[0].source_snapshot.config.mentor.mode,'manual');
  assert.equal(await page.evaluate(() => window.s5xss),undefined);
  await page.getByLabel('멘토 사용 모드').selectOption('auto');
  await page.getByLabel('자동 개입 조건',{exact:true}).fill('Needs help');
  await page.getByRole('button',{name:'패널 추가',exact:true}).click();
  const model = await page.getByLabel('패널 1 제공자 / 모델',{exact:true}).inputValue();
  await page.getByLabel('패널 2 제공자 / 모델',{exact:true}).selectOption(model);
  await page.getByLabel('패널 2 최대 출력 토큰',{exact:true}).fill('1501');
  await start.click();
  assert.match(await page.locator('#scenario-comparison').innerText(),/개입 판단 시험: 수업의 시작 턴·간격·횟수 제한은 적용하지 않음/);
  const p2 = page.getByRole('article',{name:'패널 2',exact:true});
  await p1.getByText('멘토 미개입',{exact:true}).waitFor();
  await p2.getByText(coaching,{exact:true}).waitFor();
  assert(!await p1.getByRole('button',{name:'학생 응답 채택',exact:true}).count());
  await page.getByLabel('멘토 사용 모드').selectOption('manual');
  await page.getByRole('button',{name:'패널 추가',exact:true}).click();
  await page.getByLabel('패널 3 제공자 / 모델',{exact:true}).selectOption(model);
  for (const [panel, budget] of [[1,1800],[2,1801],[3,1801]]) await page.getByLabel(`패널 ${panel} 최대 출력 토큰`,{exact:true}).fill(String(budget));
  await start.click();
  await p1.getByText(coaching,{exact:true}).waitFor();
  await p2.getByText('처리 중',{exact:true}).waitFor();
  const p3 = page.getByRole('article',{name:'패널 3',exact:true});
  assert(!await p2.locator('.comparison-text').count(),'no provisional structured output');
  assert(await start.isDisabled());
  await p2.getByRole('button',{name:'패널 중지',exact:true}).click();
  await p2.getByText('취소',{exact:true}).waitFor();
  assert(await p3.getByText('처리 중',{exact:true}).isVisible());
  await page.getByRole('button',{name:'전체 중지',exact:true}).click();
  await p3.getByText('취소',{exact:true}).waitFor();
  assert(await p1.getByText(coaching,{exact:true}).isVisible());
  assert(await start.isEnabled());
  assert(!(await page.locator('#scenario-comparison').innerText()).includes('PRIVATE MENTOR REASON'));
  await p1.getByRole('button',{name:'이 모델 적용',exact:true}).click();
  assert.equal(await page.getByLabel('멘토 최대 출력 토큰',{exact:true}).inputValue(),'1800');
  assert.equal(await page.locator('[id="student.resolved_model_config"]').inputValue(),'1');
  assert.equal(requests.length,3);
  assert.deepEqual(errors,[]);
} finally { await browser.close(); }
