import assert from 'node:assert/strict';
import {comparisonFixture, openComparison, hidden} from './s5_browser_fixtures.mjs';

export default async function checkComparisonRolesAndHistory(page) {
  page.setDefaultTimeout(3000);
  const fixture = await comparisonFixture(page, ['ok','degraded','failed']);
  await openComparison(page);
  const mentorBefore = await page.locator('[id="mentor.resolved_model_config"]').inputValue();
  await page.getByLabel('제목',{exact:true}).fill('내 수정 제목');
  await page.getByRole('button',{name:'완료 쌍 추가',exact:true}).click();
  await page.getByLabel('이력 1 교사').fill('이유가 무엇인가요?');
  await page.getByLabel('이력 1 학생').fill('분모가 더 커요.');
  await page.getByLabel('비교 대상').selectOption('analysis');
  await page.getByRole('button',{name:'비교 실행',exact:true}).click();
  const p2 = page.getByRole('article',{name:'패널 2',exact:true});
  await p2.getByRole('heading',{name:'검증된 비교 분석: 부분 분석',exact:true}).waitFor();
  assert.match(await p2.innerText(), /대화 검토: 6 \/ 7개 메시지/);
  assert.match(await p2.innerText(), /첫 본문 N\/A/);
  assert(!(await page.locator('#scenario-comparison').innerText()).includes(hidden));
  assert.equal(await page.getByRole('button',{name:'학생 응답 채택',exact:true}).count(),0);
  await page.getByRole('article',{name:'패널 3',exact:true}).getByRole('button',{name:'이 모델 적용',exact:true}).click();
  assert.equal(await page.getByLabel('사후 분석 제공자 / 모델').inputValue(),'3');
  assert.equal(await page.locator('[id="mentor.resolved_model_config"]').inputValue(),mentorBefore);
  assert.equal(await page.locator('#title').inputValue(),'내 수정 제목');
  assert(await page.getByLabel('사후 분석 제공자 / 모델').evaluate(el => document.activeElement === el));
  assert.match(await page.locator('#scenario-comparison').innerText(), /별도 저장 또는 게시/);
  await page.getByRole('button',{name:'비교 이력',exact:true}).click();
  await page.getByRole('button',{name:'과거 비교 상세',exact:true}).click();
  const detail = page.getByRole('region',{name:'비교 이력 상세',exact:true});
  await detail.waitFor();
  assert.match(await detail.innerText(), /30일|만료/);
  assert.equal(await page.locator('#title').inputValue(),'내 수정 제목');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button',{name:'비교 기록 삭제',exact:true}).click();
  await page.getByText('비교 기록을 삭제했습니다. 발생한 비용 원장은 보존됩니다.', {exact:true}).waitFor();
  assert.equal(await page.getByRole('region',{name:'비교 이력 목록',exact:true}).getByRole('button').count(),0);
  await page.route('**/admin/comparisons', route => route.fulfill({json:{items:[{comparison_run_id:'comparison-1',title:'과거 비교',target_role:'analysis',created_at:'2026-10-11',status:'finished'}],next_cursor:null}}));
  await page.route('**/admin/comparisons/comparison-1',route => route.fulfill({status:404,json:{detail:'Not found'}}));
  await page.getByRole('button',{name:'비교 이력',exact:true}).click();
  await page.getByRole('button',{name:'과거 비교 상세',exact:true}).click();
  await page.getByText(/비교가 만료되었거나 삭제되었습니다/).waitFor();
  assert.equal(await detail.getByRole('button',{name:'이 모델 적용',exact:true}).count(),0);
  assert.equal(fixture.requests[0].target_role,'analysis');
  return {pageErrors:[]};
}
